<script setup lang="ts">
/**
 * Embeds a sheet of a real generated example workbook, drawn natively like the playground.
 *
 * ::workbook-preview{artifact="kitchen-sink" sheet="06 Badges Checkboxes"}
 * ::
 */
import { computed } from "vue";
import XlsxSheet from "../playground/XlsxSheet.vue";
import { loadWorkbookPreview } from "../playground/xlsx";

const props = withDefaults(
  defineProps<{
    artifact: string;
    sheet?: string;
    caption?: string;
    zoom?: number;
    maxHeight?: number;
  }>(),
  { zoom: 0.82, maxHeight: 420 },
);

const { data: model } = await useAsyncData(`workbook-preview:${props.artifact}`, () =>
  loadWorkbookPreview(props.artifact),
);
const index = computed(() => {
  const sheets = model.value?.sheets ?? [];
  const i = props.sheet ? sheets.findIndex((s) => s.name === props.sheet) : 0;
  return Math.max(0, i);
});
const sheet = computed(() => model.value?.sheets[index.value] ?? null);
const href = computed(() => `/playground/${props.artifact}?sheet=${index.value}`);
</script>

<template>
  <figure v-if="model && sheet" class="wp not-prose">
    <div class="wp-frame">
      <div class="wp-bar">
        <span class="wp-file"
          ><UIcon name="i-lucide-sheet" class="wp-ic" />{{ artifact }}.xlsx</span
        >
        <NuxtLink :to="href" class="wp-open"
          >Open in playground <UIcon name="i-lucide-arrow-up-right" class="wp-ic"
        /></NuxtLink>
      </div>
      <div class="wp-scroll" :style="{ maxHeight: `${maxHeight}px` }">
        <XlsxSheet
          :sheet="sheet"
          :styles="model.styles"
          :dxfs="model.dxfs"
          :zoom="zoom"
          :extra-rows="2"
        />
      </div>
      <div class="wp-tabs">
        <span>{{ sheet.name }}</span>
      </div>
    </div>
    <figcaption>
      {{ caption ?? "Drawn from the real file generated by the examples package." }}
    </figcaption>
  </figure>
</template>

