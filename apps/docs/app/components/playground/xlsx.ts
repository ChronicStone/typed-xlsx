/* ---------- schema source ↔ sheet columns ---------- */

export interface SchemaColumnBlock {
  id: string;
  header?: string;
  schema?: string;
  /** 0-based line range in the source, inclusive */
  start: number;
  end: number;
}

/** Finds `.column("id", { … })` blocks and the schema chain each one belongs to. */
export function findColumnBlocks(lines: string[]): SchemaColumnBlock[] {
  const blocks: SchemaColumnBlock[] = [];
  let schema: string | undefined;
  let open: SchemaColumnBlock | null = null;
  let depth = 0;
  lines.forEach((line, i) => {
    const decl = line.match(/(?:const|let)\s+(\w+)\s*=\s*createExcelSchema/);
    if (decl) schema = decl[1];
    const col = line.match(/^\s*\.column\(\s*"([^"]+)"/);
    if (col && !open) {
      open = { id: col[1]!, schema, start: i, end: i };
      depth = 0;
    }
    if (open) {
      for (const ch of line) {
        if (ch === "(" || ch === "{" || ch === "[") depth++;
        else if (ch === ")" || ch === "}" || ch === "]") depth--;
      }
      const header = line.match(/^\s*header:\s*"([^"]+)"/);
      if (header && !open.header) open.header = header[1];
      if (depth <= 0) {
        open.end = i;
        blocks.push(open);
        open = null;
      }
    }
    if (/^\s*\.build\(\)/.test(line)) schema = undefined;
  });
  return blocks;
}

/** The schema variable a sheet's table uses, read from workbook.ts / stream.ts. */
export function schemaForSheet(workbookSource: string, sheetName: string) {
  const at = workbookSource.indexOf(`"${sheetName}"`);
  if (at < 0) return undefined;
  const after = workbookSource.slice(at, at + 1600);
  return after.match(/schema:\s*(\w+)/)?.[1];
}

const humanize = (id: string) =>
  id
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/[_-]+/g, " ")
    .toLowerCase()
    .trim();

/** Maps each column block to a sheet column by matching its header text in the first rows. */
export function mapBlocksToColumns(
  blocks: SchemaColumnBlock[],
  cells: Record<string, { v: string }>,
  schema: string | undefined,
  searchRows = 8,
) {
  const headerCells = new Map<string, number>();
  for (const [ref, cell] of Object.entries(cells)) {
    const p = parseCellRef(ref);
    if (!p || p.r > searchRows || !cell.v) continue;
    const k = cell.v.trim().toLowerCase();
    if (!headerCells.has(k)) headerCells.set(k, p.c);
  }
  const scoped =
    schema && blocks.some((b) => b.schema === schema)
      ? blocks.filter((b) => b.schema === schema)
      : blocks;
  const out = new Map<SchemaColumnBlock, number>();
  for (const block of scoped) {
    const candidates = [
      block.header?.toLowerCase(),
      block.id.toLowerCase(),
      humanize(block.id),
    ].filter(Boolean) as string[];
    const hit = candidates.map((c) => headerCells.get(c)).find((c) => c != null);
    if (hit != null) out.set(block, hit);
  }
  return out;
}

export function formatXml(input: string) {
  const parts = input.replace(/>\s+</g, "><").match(/<[^>]+>|[^<]+/g) ?? [];
  const out: string[] = [];
  let depth = 0;
  const pad = () => "  ".repeat(depth);
  for (let i = 0; i < parts.length; i++) {
    const p = parts[i]!;
    if (p.startsWith("</")) {
      depth = Math.max(0, depth - 1);
      out.push(pad() + p);
    } else if (p.startsWith("<?") || p.startsWith("<!") || p.endsWith("/>")) {
      out.push(pad() + p);
    } else if (p.startsWith("<")) {
      const text = parts[i + 1];
      const close = parts[i + 2];
      if (text && !text.startsWith("<") && close?.startsWith("</")) {
        // <v>8</v> stays on one line
        out.push(pad() + p + text + close);
        i += 2;
      } else if (text?.startsWith("</")) {
        out.push(pad() + p + text);
        i += 1;
      } else {
        out.push(pad() + p);
        depth++;
      }
    } else if (p.trim()) {
      out.push(pad() + p.trim());
    }
  }
  return out.join("\n");
}
