export function colLetter(n: number) {
  let s = "";
  while (n > 0) {
    const m = (n - 1) % 26;
    s = String.fromCharCode(65 + m) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

export function colIndex(letters: string) {
  let n = 0;
  for (const ch of letters) n = n * 26 + (ch.charCodeAt(0) - 64);
  return n;
}

export function parseCellRef(ref: string) {
  const m = ref.replace(/\$/g, "").match(/^([A-Z]+)(\d+)$/);
  return m ? { c: colIndex(m[1]!), r: Number(m[2]) } : null;
}

export function parseRangeRef(ref: string) {
  const [a, b] = ref.split(":");
  const s = parseCellRef(a ?? "");
  const e = parseCellRef(b ?? a ?? "");
  if (!s || !e) return null;
  return {
    r1: Math.min(s.r, e.r),
    c1: Math.min(s.c, e.c),
    r2: Math.max(s.r, e.r),
    c2: Math.max(s.c, e.c),
  };
}

/** Approximate colors of Excel's built-in table styles (Light / Medium / Dark 1–28). */
const ACCENTS = ["#404040", "#4472c4", "#ed7d31", "#a5a5a5", "#ffc000", "#5b9bd5", "#70ad47"];
const mix = (hex: string, white: number) => {
  const n = Number.parseInt(hex.slice(1), 16);
  const ch = (shift: number) => Math.round(((n >> shift) & 255) * (1 - white) + 255 * white);
  return `rgb(${ch(16)}, ${ch(8)}, ${ch(0)})`;
};
export function tableStyleColors(name: string) {
  const m = name.match(/TableStyle(Light|Medium|Dark)(\d+)/);
  const family = m?.[1] ?? "Medium";
  const n = Number(m?.[2] ?? 2);
  const accent = ACCENTS[(n - 1) % 7]!;
  if (family === "Light") {
    const filled = n >= 8 && n <= 14;
    return {
      head: filled ? accent : "transparent",
      headText: filled ? "#ffffff" : "#000000",
      band: n <= 7 ? mix(accent, 0.82) : n >= 15 ? mix(accent, 0.82) : null,
      line: accent,
    };
  }
  if (family === "Dark")
    return { head: "#000000", headText: "#ffffff", band: mix(accent, 0.55), line: "#000000" };
  return { head: accent, headText: "#ffffff", band: mix(accent, 0.8), line: accent };
}

