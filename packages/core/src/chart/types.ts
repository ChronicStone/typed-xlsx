// ── Options ──────────────────────────────────────────────────────────────────

export type ChartMarkType = "bar" | "line" | "area" | "scatter" | "pie" | "doughnut";
export type ChartLegendPosition = "top" | "bottom" | "left" | "right";
/** Value axis a mark is drawn against. `"y2"` is the secondary axis on the right. */
export type ChartAxisId = "y" | "y2";

/** Hex color such as `"#2563EB"` or `"2563EB"`. */
export type ChartColor = string;

export interface ChartDataLabels {
  /** Show the value. Defaults to `true`. */
  value?: boolean;
  /** Show the category (x value or slice label). */
  category?: boolean;
  /** Show the series name. */
  series?: boolean;
  /** Show the share of the total. Pie and doughnut only. */
  percent?: boolean;
  /** Excel number format for the labels, such as `"#,##0"` or `"0.0%"`. */
  format?: string;
}

export interface ChartSeriesStyle {
  /** Legend label. Defaults to the column header, linked to its cell. */
  name?: string;
  color?: ChartColor;
}

export interface ChartCategoryAxisOptions {
  title?: string;
  hidden?: boolean;
  gridlines?: boolean;
  reverse?: boolean;
}

export interface ChartValueAxisOptions {
  title?: string;
  hidden?: boolean;
  /** Horizontal gridlines. Defaults to `true` on `y`. */
  gridlines?: boolean;
  reverse?: boolean;
  min?: number;
  max?: number;
  /** Distance between major ticks. */
  step?: number;
  /** Excel number format. Defaults to the format of the source cells. */
  format?: string;
  /** Logarithmic scale base, such as `10`. */
  logBase?: number;
}

export interface ChartAxes {
  /** Category axis, or the horizontal value axis of a scatter chart. */
  x?: ChartCategoryAxisOptions & ChartValueAxisOptions;
  y?: ChartValueAxisOptions;
  y2?: ChartValueAxisOptions;
}

export interface ChartSize {
  /** Width in pixels. Defaults to 600. */
  width?: number;
  /** Height in pixels. Defaults to 320. */
  height?: number;
}

// ── Column filtering ─────────────────────────────────────────────────────────

type Present<T> = Exclude<T, null | undefined>;

type ColumnsMatching<TColumns, TValue> = {
  [K in keyof TColumns]-?: unknown extends TColumns[K]
    ? K
    : [Present<TColumns[K]>] extends [never]
      ? never
      : [Present<TColumns[K]>] extends [TValue]
        ? K
        : never;
}[keyof TColumns] &
  string;

/** Columns whose cells hold numbers. Only these can be plotted as values. */
export type ChartNumericColumn<TColumns> = ColumnsMatching<TColumns, number>;
/** Columns that can label categories: text, numbers, dates or booleans. */
export type ChartCategoryColumn<TColumns> = ColumnsMatching<
  TColumns,
  string | number | boolean | Date
>;

export type ChartSeriesInput<TColumns, TDynamic extends string> =
  | ChartNumericColumn<TColumns>
  | ({ column: ChartNumericColumn<TColumns> } & ChartSeriesStyle)
  | { dynamic: TDynamic };

export type ChartValuesInput<TColumns, TDynamic extends string> =
  | ChartSeriesInput<TColumns, TDynamic>
  | readonly ChartSeriesInput<TColumns, TDynamic>[];

// ── Mark options ─────────────────────────────────────────────────────────────

interface ChartSeriesMarkOptions<TColumns, TDynamic extends string> {
  /**
   * Categories. A column (one category per row), or `{ dynamic }` to use the columns
   * generated by a dynamic block as categories, with one series per row.
   */
  x: ChartCategoryColumn<TColumns> | { dynamic: TDynamic };
  /** Numeric column(s) to plot, one series each. */
  y?: ChartValuesInput<TColumns, TDynamic>;
  /** With `x: { dynamic }`: column naming each row's series. */
  series?: ChartCategoryColumn<TColumns>;
  /** Legend label when `y` is a single column. */
  name?: string;
  /** Color when `y` is a single column. */
  color?: ChartColor;
  labels?: boolean | ChartDataLabels;
  /** Plot against the secondary value axis. Defaults to `"y"`. */
  axis?: ChartAxisId;
}

export interface ChartBarOptions<TColumns, TDynamic extends string> extends ChartSeriesMarkOptions<
  TColumns,
  TDynamic
> {
  /** Stack series on top of each other, or as shares of 100%. */
  stack?: boolean | "percent";
  /** Draw bars horizontally. Horizontal bars cannot share a chart with other marks. */
  horizontal?: boolean;
  /** Space between bar groups, as a percentage of a bar's width (0-500). Defaults to 150. */
  gap?: number;
}

export interface ChartLineOptions<TColumns, TDynamic extends string> extends ChartSeriesMarkOptions<
  TColumns,
  TDynamic
> {
  stack?: boolean | "percent";
  smooth?: boolean;
  /** Draw a marker on each point. Defaults to `true`. */
  markers?: boolean;
  dashed?: boolean;
  /** Line width in points. */
  width?: number;
}

export interface ChartAreaOptions<TColumns, TDynamic extends string> extends ChartSeriesMarkOptions<
  TColumns,
  TDynamic
> {
  stack?: boolean | "percent";
}

export interface ChartScatterOptions<TColumns, TDynamic extends string> {
  /** Numeric column for the horizontal position. */
  x: ChartNumericColumn<TColumns>;
  y: ChartValuesInput<TColumns, TDynamic>;
  name?: string;
  color?: ChartColor;
  labels?: boolean | ChartDataLabels;
  /** Join the points with a line. Defaults to `false`. */
  lines?: boolean;
  smooth?: boolean;
  markers?: boolean;
}

export interface ChartPieOptions<TColumns> {
  /** Column labelling each slice. */
  label: ChartCategoryColumn<TColumns>;
  /** Numeric column sizing each slice. */
  value: ChartNumericColumn<TColumns>;
  name?: string;
  /** Slice colors, in row order. */
  colors?: readonly ChartColor[];
  labels?: boolean | ChartDataLabels;
}

export interface ChartDoughnutOptions<TColumns> extends ChartPieOptions<TColumns> {
  /** Size of the hole as a percentage of the doughnut (10-90). Defaults to 55. */
  hole?: number;
}

type IsSingleSeries<TY> = TY extends string ? true : TY extends { column: string } ? true : false;

/** Readable `✗ …` requirements for options that only make sense together. */
type ChartSeriesOptionProblems<TOptions> = TOptions extends { x: { dynamic: string } }
  ?
      | (TOptions extends { series: string }
          ? never
          : "a mark with x: { dynamic } needs series: the column naming each row")
      | (TOptions extends { y: unknown }
          ? "a mark with x: { dynamic } takes its values from the dynamic columns, so drop y"
          : never)
  :
      | (TOptions extends { y: unknown } ? never : "this mark needs y: the column(s) to plot")
      | (TOptions extends { series: unknown } ? "series only applies with x: { dynamic }" : never)
      | (TOptions extends { y: infer TY }
          ? IsSingleSeries<TY> extends true
            ? never
            : TOptions extends { name: unknown } | { color: unknown }
              ? "name and color apply to a single y column; set them per column with { column, name, color }"
              : never
          : never);

export type ChartSeriesOptionsGuard<TOptions> = [ChartSeriesOptionProblems<TOptions>] extends [
  never,
]
  ? unknown
  : { [TProblem in ChartSeriesOptionProblems<TOptions> as `✗ ${TProblem}`]: true };

// ── Marks ────────────────────────────────────────────────────────────────────

/** Mark variants that matter for combination rules. */
export type ChartMarkVariant = ChartMarkType | "horizontal-bar" | "pivot" | "pivot-invalid-pie";

/** A layer of a chart, created from a table with `refs.table(id).bar(...)`, `.line(...)`, … */
export interface ChartMark<TVariant extends ChartMarkVariant = ChartMarkVariant, TX = unknown> {
  readonly kind: "chart-mark";
  readonly type: ChartMarkType;
  /** Table the mark reads, or the pivot when `pivot` is set. */
  readonly source: { readonly sheet: string; readonly table: string; readonly pivot?: boolean };
  readonly options: Readonly<Record<string, unknown>>;
  readonly __variant?: TVariant;
  readonly __x?: TX;
}

type ChartXValue<TColumns, TX> = TX extends { dynamic: string }
  ? string
  : TX extends keyof TColumns
    ? TColumns[TX]
    : unknown;

/** Mark factories of one table. Field names are checked against the table's rendered columns. */
export interface ChartTable<TColumns = Record<string, unknown>, TDynamic extends string = string> {
  bar<const TOptions extends ChartBarOptions<TColumns, TDynamic>>(
    options: TOptions & ChartSeriesOptionsGuard<TOptions>,
  ): ChartMark<
    TOptions extends { horizontal: true } ? "horizontal-bar" : "bar",
    ChartXValue<TColumns, TOptions["x"]>
  >;
  line<const TOptions extends ChartLineOptions<TColumns, TDynamic>>(
    options: TOptions & ChartSeriesOptionsGuard<TOptions>,
  ): ChartMark<"line", ChartXValue<TColumns, TOptions["x"]>>;
  area<const TOptions extends ChartAreaOptions<TColumns, TDynamic>>(
    options: TOptions & ChartSeriesOptionsGuard<TOptions>,
  ): ChartMark<"area", ChartXValue<TColumns, TOptions["x"]>>;
  scatter<const TOptions extends ChartScatterOptions<TColumns, TDynamic>>(
    options: TOptions & ChartSeriesOptionsGuard<TOptions>,
  ): ChartMark<"scatter", number>;
  pie<const TOptions extends ChartPieOptions<TColumns>>(
    options: TOptions,
  ): ChartMark<"pie", ChartXValue<TColumns, TOptions["label"]>>;
  doughnut<const TOptions extends ChartDoughnutOptions<TColumns>>(
    options: TOptions,
  ): ChartMark<"doughnut", ChartXValue<TColumns, TOptions["label"]>>;
  /**
   * A native Excel pivot table over this table, for `sheet.pivot(id, …)`.
   *
   * @example
   * refs.table("sales").pivot({ rows: ["region"], columns: ["month"], values: { revenue: "sum" } })
   */
  pivot<const TOptions extends PivotOptions<TColumns>>(
    options: TOptions & PivotOptionsGuard<TOptions>,
  ): PivotSpec<PivotShapeOf<TOptions>>;
}

// ── Chart spec and combination rules ─────────────────────────────────────────

export interface ChartSpec<TMarks extends readonly ChartMark<any, any>[] = readonly ChartMark[]> {
  title?: string;
  /** Layers of the chart, drawn in order. */
  marks: TMarks;
  axes?: ChartAxes;
  /** Defaults to `"bottom"` when the chart has several series or slices, hidden otherwise. */
  legend?: ChartLegendPosition | false;
  /** Palette used, in order, for series without their own color. */
  colors?: readonly ChartColor[];
  /** Top-left cell, such as `"B2"`. Defaults to the right of the sheet's tables. */
  at?: string;
  size?: ChartSize;
}

type VariantOf<TMark> = TMark extends ChartMark<infer TVariant, any> ? TVariant : never;
type XOf<TMark> = TMark extends ChartMark<any, infer TX> ? TX : never;

type XKind<TX> = unknown extends TX
  ? never
  : Present<TX> extends Date
    ? "dates"
    : Present<TX> extends number
      ? "numbers"
      : Present<TX> extends boolean
        ? "booleans"
        : Present<TX> extends string
          ? "text"
          : never;

type CategoryMarks<TMarks extends readonly unknown[]> = Extract<
  TMarks[number],
  ChartMark<"bar" | "horizontal-bar" | "line" | "area", any>
>;

type CategoryXKinds<TMarks extends readonly unknown[]> =
  CategoryMarks<TMarks> extends infer TMark
    ? TMark extends unknown
      ? XKind<XOf<TMark>>
      : never
    : never;

type IsUnion<T, TAll = T> = T extends unknown ? ([TAll] extends [T] ? false : true) : never;

type Has<TMarks extends readonly unknown[], TVariant> = [
  Extract<VariantOf<TMarks[number]>, TVariant>,
] extends [never]
  ? false
  : true;

type HasOther<TMarks extends readonly unknown[], TVariant> = [
  Exclude<VariantOf<TMarks[number]>, TVariant>,
] extends [never]
  ? false
  : true;

type ChartMarkProblems<TMarks extends readonly unknown[]> =
  | (Has<TMarks, "pivot" | "pivot-invalid-pie"> extends true
      ? TMarks["length"] extends 1
        ? never
        : "a pivot chart takes a single mark"
      : never)
  | (Has<TMarks, "pivot-invalid-pie"> extends true
      ? "a pivot pie needs a pivot without columns and with a single value"
      : never)
  | (Has<TMarks, "pie" | "doughnut"> extends true
      ? TMarks["length"] extends 1
        ? never
        : "a pie or doughnut chart takes a single mark"
      : never)
  | (Has<TMarks, "scatter"> extends true
      ? HasOther<TMarks, "scatter"> extends true
        ? "scatter marks cannot share a chart with other marks"
        : never
      : never)
  | (Has<TMarks, "horizontal-bar"> extends true
      ? HasOther<TMarks, "horizontal-bar"> extends true
        ? "horizontal bars cannot share a chart with other marks"
        : never
      : never)
  | (true extends IsUnion<CategoryXKinds<TMarks>>
      ? `marks disagree on the x axis: ${CategoryXKinds<TMarks>}`
      : never);

/** Adds readable `✗ …` requirements when marks cannot be combined in one Excel chart. */
export type ChartSpecGuard<TMarks extends readonly unknown[]> = [
  ChartMarkProblems<TMarks>,
] extends [never]
  ? unknown
  : { [TProblem in ChartMarkProblems<TMarks> as `✗ ${TProblem}`]: true };

// ── Chain registry ───────────────────────────────────────────────────────────

/** Columns and dynamic blocks a table renders once its `select` is applied. */
export interface ChartTableShape<
  TColumns = Record<string, unknown>,
  TDynamic extends string = string,
> {
  readonly columns: TColumns;
  readonly dynamic: TDynamic;
}

type ChartTableIdsOf<TBook, TSheet extends string> = TSheet extends keyof TBook
  ? {
      [K in keyof TBook[TSheet]]: TBook[TSheet][K] extends ChartTableShape ? K : never;
    }[keyof TBook[TSheet]] &
      string
  : never;

type ChartPivotIdsOf<TBook, TSheet extends string> = TSheet extends keyof TBook
  ? {
      [K in keyof TBook[TSheet]]: TBook[TSheet][K] extends PivotShape ? K : never;
    }[keyof TBook[TSheet]] &
      string
  : never;

type ChartPivotOf<TBook, TSheet extends string, TPivot extends string> = TSheet extends keyof TBook
  ? TPivot extends keyof TBook[TSheet]
    ? TBook[TSheet][TPivot] extends PivotShape<infer TPie>
      ? PivotChartSource<TPie>
      : never
    : never
  : never;

type ChartTableOf<TBook, TSheet extends string, TTable extends string> = TSheet extends keyof TBook
  ? TTable extends keyof TBook[TSheet]
    ? TBook[TSheet][TTable] extends ChartTableShape<infer TColumns, infer TDynamic>
      ? ChartTable<TColumns, TDynamic>
      : never
    : never
  : never;

export interface ChartSheetRefs<TBook, TSheet extends string> {
  /** A table of this sheet, declared earlier in the chain. */
  table<const TTable extends ChartTableIdsOf<TBook, TSheet>>(
    tableId: TTable,
  ): ChartTableOf<TBook, TSheet, TTable>;
  /** A pivot of this sheet, declared earlier in the chain. */
  pivot<const TPivot extends ChartPivotIdsOf<TBook, TSheet>>(
    pivotId: TPivot,
  ): ChartPivotOf<TBook, TSheet, TPivot>;
}

/**
 * Tables declared earlier in the chain. `refs.table(id)` looks on the current sheet;
 * `refs.sheet(name).table(id)` on another one.
 */
export interface ChartRefs<TBook, TSheet extends string> extends ChartSheetRefs<TBook, TSheet> {
  sheet<const TOtherSheet extends keyof TBook & string>(
    sheetName: TOtherSheet,
  ): ChartSheetRefs<TBook, TOtherSheet>;
}

type Simplify<T> = { [K in keyof T]: T[K] } & unknown;

export type EmptyChartBook = Record<never, never>;

export type ChartBookAddSheet<TBook, TSheet extends string> = Simplify<
  TBook & { [K in TSheet]: Record<never, never> }
>;

/** Registers a table on a sheet. A duplicate id (already a type error) keeps the first table. */
export type ChartBookAddTable<
  TBook,
  TSheet extends string,
  TTable extends string,
  TShape,
> = TSheet extends keyof TBook
  ? TTable extends keyof TBook[TSheet]
    ? TBook
    : Simplify<
        Omit<TBook, TSheet> & {
          [K in TSheet]: Simplify<TBook[TSheet] & { [Q in TTable]: TShape }>;
        }
      >
  : Simplify<TBook & { [K in TSheet]: { [Q in TTable]: TShape } }>;

export type ChartSheetNameGuard<TName extends string, TBook> = string extends TName
  ? unknown
  : TName extends keyof TBook
    ? { readonly [P in `✗ sheet "${TName}" already exists`]: true }
    : unknown;

export type ChartPivotIdGuard<
  TPivot extends string,
  TBook,
  TSheet extends string,
> = string extends TPivot
  ? unknown
  : TSheet extends keyof TBook
    ? TPivot extends keyof TBook[TSheet]
      ? { readonly [P in `✗ "${TPivot}" is already used on this sheet`]: true }
      : unknown
    : unknown;

export type ChartTableIdGuard<
  TTable extends string,
  TBook,
  TSheet extends string,
> = string extends TTable
  ? unknown
  : TSheet extends keyof TBook
    ? TTable extends keyof TBook[TSheet]
      ? { readonly [P in `✗ table "${TTable}" already exists on this sheet`]: true }
      : unknown
    : unknown;

type SelectedIds<TAll, TSelection> = (
  TSelection extends { include: readonly (infer TIncluded)[] }
    ? [Exclude<TIncluded, TAll>] extends [never]
      ? Extract<TAll, TIncluded>
      : TAll
    : TAll
) extends infer TIncludedIds
  ? TSelection extends { exclude: readonly (infer TExcluded)[] }
    ? Exclude<TIncludedIds, TExcluded>
    : TIncludedIds
  : never;

/** Shape of a table rendered from `TSchema` with `select` applied. */
export type ChartTableShapeOf<TSchema, TSelection> = ChartTableShape<
  Simplify<
    Pick<
      SchemaColumnValues<TSchema>,
      SelectedIds<SchemaColumnId<TSchema>, TSelection> & keyof SchemaColumnValues<TSchema>
    >
  >,
  SelectedIds<SchemaDynamicId<TSchema>, TSelection> & string
>;

/** Chart declared on a sheet, before its marks are resolved against the laid-out tables. */
export interface ChartPlan {
  id: string;
  spec: ChartSpec;
}
